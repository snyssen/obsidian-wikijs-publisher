import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { copyFileSync, existsSync } from 'node:fs';
import path from 'node:path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

// When set (e.g. by `just dev`), build straight into a vault's plugin folder
const pluginDir = process.env.OBSIDIAN_PLUGIN_DIR;

const copyToPluginDir = {
	name: 'copy-to-plugin-dir',
	setup(build) {
		build.onEnd(() => {
			for (const file of ['manifest.json', 'styles.css']) {
				if (existsSync(file)) copyFileSync(file, path.join(pluginDir, file));
			}
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	define: { __DEV__: JSON.stringify(!prod) },
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: pluginDir ? path.join(pluginDir, 'main.js') : 'main.js',
	plugins: pluginDir ? [copyToPluginDir] : [],
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
